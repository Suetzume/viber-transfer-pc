-- Референсная схема базы данных iOS Viber (Chat.data / Chatdata.sqlite)
-- Источник: открытые спецификации iPhone-Backup-Analyzer-2 (plg_viber.py), CoreData SQLite

CREATE TABLE IF NOT EXISTS ZCONVERSATION (
    Z_PK INTEGER PRIMARY KEY,
    Z_ENT INTEGER,
    Z_OPT INTEGER,
    ZTYPE INTEGER DEFAULT 0,
    ZDATE FLOAT,                -- Apple Cocoa Epoch (секунды от 01.01.2001)
    ZNAME VARCHAR,
    ZICONURI VARCHAR,
    ZUNREADCOUNT INTEGER DEFAULT 0,
    ZTOKEN VARCHAR
);

CREATE TABLE IF NOT EXISTS ZPARTICIPANT (
    Z_PK INTEGER PRIMARY KEY,
    Z_ENT INTEGER,
    Z_OPT INTEGER,
    ZCONVERSATION INTEGER,
    ZPHONENUMBER VARCHAR,
    ZDISPLAYNAME VARCHAR,
    ZVIBERNAME VARCHAR,
    ZISOWNER INTEGER DEFAULT 0,
    FOREIGN KEY (ZCONVERSATION) REFERENCES ZCONVERSATION(Z_PK)
);

CREATE TABLE IF NOT EXISTS ZMESSAGE (
    Z_PK INTEGER PRIMARY KEY,
    Z_ENT INTEGER,
    Z_OPT INTEGER,
    ZCONVERSATION INTEGER NOT NULL,
    ZSENDER INTEGER NOT NULL,
    ZDATE FLOAT NOT NULL,       -- Apple Cocoa Epoch (секунды от 01.01.2001)
    ZTEXT VARCHAR,
    ZMESSAGETYPE INTEGER DEFAULT 0,
    ZSTATE INTEGER DEFAULT 0,   -- 0: Отправлено, 1: Доставлено, 2: Прочитано
    ZISINCOMING INTEGER DEFAULT 0,
    ZATTACHMENTPATH VARCHAR,
    ZATTACHMENTTYPE INTEGER DEFAULT 0,
    ZMEDIAFILESIZE INTEGER DEFAULT 0,
    ZDURATION FLOAT DEFAULT 0,
    FOREIGN KEY (ZCONVERSATION) REFERENCES ZCONVERSATION(Z_PK),
    FOREIGN KEY (ZSENDER) REFERENCES ZPARTICIPANT(Z_PK)
);

CREATE INDEX IF NOT EXISTS Z_idx_message_conversation ON ZMESSAGE (ZCONVERSATION);
CREATE INDEX IF NOT EXISTS Z_idx_message_date ON ZMESSAGE (ZDATE);
