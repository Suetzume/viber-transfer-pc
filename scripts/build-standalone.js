/**
 * Standalone Packager: Сборщик автономного исполняемого файла ViberTransfer.exe для Windows.
 * 
 * Использует встроенный в Node.js механизм Single Executable Application (Node SEA).
 * Упаковывает всё приложение (весь движок, сервер, коннекторы, схемы БД и веб-интерфейс)
 * в один самостоятельный бинарный файл без внешних зависимостей.
 */

const fs = require('node:fs');
const path = require('node:path');
const { execSync } = require('node:child_process');

const ROOT_DIR = path.resolve(__dirname, '..');
const DIST_DIR = path.join(ROOT_DIR, 'dist');

console.log('='.repeat(70));
console.log('📦 СБОРКА АВТОНОМНОГО ИСПОЛНЯЕМОГО ФАЙЛА ViberTransfer.exe');
console.log('='.repeat(70));

if (!fs.existsSync(DIST_DIR)) {
  fs.mkdirSync(DIST_DIR, { recursive: true });
}

// 1. Читаем статические ресурсы для виртуального внедрения
console.log('[1/5] Встраивание статических ресурсов и DDL-схем...');
const indexHtml = fs.readFileSync(path.join(ROOT_DIR, 'src/renderer/index.html'), 'utf8');
const androidSql = fs.readFileSync(path.join(ROOT_DIR, 'fixtures/schemas/android_viber_messages.sql'), 'utf8');
const iosSql = fs.readFileSync(path.join(ROOT_DIR, 'fixtures/schemas/ios_viber_chat.sql'), 'utf8');
const manifestSql = fs.readFileSync(path.join(ROOT_DIR, 'fixtures/schemas/sample_manifest.sql'), 'utf8');

// 2. Список всех модулей системы
const modules = [
  { id: 'foundation/time-engine', file: 'src/engine/foundation/time-engine.js' },
  { id: 'foundation/hash-service', file: 'src/engine/foundation/hash-service.js' },
  { id: 'uim/contracts', file: 'src/engine/uim/contracts.js' },
  { id: 'uim/validator', file: 'src/engine/uim/validator.js' },
  { id: 'adapters/android-adapter', file: 'src/engine/adapters/android-adapter.js' },
  { id: 'adapters/key-rebalancer', file: 'src/engine/adapters/key-rebalancer.js' },
  { id: 'adapters/ios-adapter', file: 'src/engine/adapters/ios-adapter.js' },
  { id: 'manifest/manifest-builder', file: 'src/engine/manifest/manifest-builder.js' },
  { id: 'backup/zip-handler', file: 'src/engine/backup/zip-handler.js' },
  { id: 'pipeline/media-pipeline', file: 'src/engine/pipeline/media-pipeline.js' },
  { id: 'pipeline/migration-engine', file: 'src/engine/pipeline/migration-engine.js' },
  { id: 'devices/android-connector', file: 'src/devices/android/adb-connector.js' },
  { id: 'devices/ios-connector', file: 'src/devices/ios/ios-connector.js' },
  { id: 'devices/desktop-launcher', file: 'src/devices/desktop/viber-desktop-launcher.js' },
  { id: 'devices/index', file: 'src/devices/index.js' },
  { id: 'server/bridge-server', file: 'src/server/bridge-server.js' }
];

// 3. Формирование монолитного bundle.js
console.log('[2/5] Сборка монолитного бандла JavaScript...');
let bundleCode = `
/**
 * Viber Transfer PC Standalone Monolithic Bundle
 * Auto-generated by build-standalone.js
 */

const __VIRTUAL_ASSETS__ = {
  'index.html': ${JSON.stringify(indexHtml)},
  'android_viber_messages.sql': ${JSON.stringify(androidSql)},
  'ios_viber_chat.sql': ${JSON.stringify(iosSql)},
  'sample_manifest.sql': ${JSON.stringify(manifestSql)}
};

global.__EMBEDDED_INDEX_HTML__ = __VIRTUAL_ASSETS__['index.html'];
global.__VIRTUAL_ASSETS__ = __VIRTUAL_ASSETS__;

// Перехват fs.readFileSync для чтения встроенных виртуальных ресурсов
const __node_fs = require('node:fs');
const __originalReadFileSync = __node_fs.readFileSync;
__node_fs.readFileSync = function(targetPath, options) {
  if (typeof targetPath === 'string') {
    const base = require('node:path').basename(targetPath);
    if (__VIRTUAL_ASSETS__[base] !== undefined) {
      const encoding = typeof options === 'string' ? options : (options && options.encoding);
      if (encoding === 'utf8' || encoding === 'utf-8') {
        return __VIRTUAL_ASSETS__[base];
      }
      return Buffer.from(__VIRTUAL_ASSETS__[base], 'utf8');
    }
  }
  return __originalReadFileSync.apply(this, arguments);
};

const __MODULE_REGISTRY__ = {};
const __MODULE_CACHE__ = {};

function __define(id, factory) {
  __MODULE_REGISTRY__[id] = factory;
}

function __resolve(fromId, reqPath) {
  if (reqPath.startsWith('node:')) return reqPath;
  if (reqPath === 'node:fs' || reqPath === 'node:path' || reqPath === 'node:os' ||
      reqPath === 'node:sqlite' || reqPath === 'node:child_process' || 
      reqPath === 'node:zlib' || reqPath === 'node:crypto' || reqPath === 'node:http') {
    return reqPath;
  }

  // Нормализация путей
  if (reqPath.includes('time-engine')) return 'foundation/time-engine';
  if (reqPath.includes('hash-service')) return 'foundation/hash-service';
  if (reqPath.includes('contracts')) return 'uim/contracts';
  if (reqPath.includes('validator')) return 'uim/validator';
  if (reqPath.includes('android-adapter')) return 'adapters/android-adapter';
  if (reqPath.includes('key-rebalancer')) return 'adapters/key-rebalancer';
  if (reqPath.includes('ios-adapter')) return 'adapters/ios-adapter';
  if (reqPath.includes('manifest-builder')) return 'manifest/manifest-builder';
  if (reqPath.includes('zip-handler')) return 'backup/zip-handler';
  if (reqPath.includes('media-pipeline')) return 'pipeline/media-pipeline';
  if (reqPath.includes('migration-engine')) return 'pipeline/migration-engine';
  if (reqPath.includes('adb-connector')) return 'devices/android-connector';
  if (reqPath.includes('ios-connector')) return 'devices/ios-connector';
  if (reqPath.includes('viber-desktop-launcher')) return 'devices/desktop-launcher';
  if (reqPath.includes('devices')) return 'devices/index';
  if (reqPath.includes('bridge-server')) return 'server/bridge-server';

  return reqPath;
}

function __app_require(fromId) {
  return function(reqPath) {
    const resolved = __resolve(fromId, reqPath);
    if (__MODULE_REGISTRY__[resolved]) {
      if (!__MODULE_CACHE__[resolved]) {
        const module = { exports: {} };
        __MODULE_CACHE__[resolved] = module;
        __MODULE_REGISTRY__[resolved](module, module.exports, __app_require(resolved));
      }
      return __MODULE_CACHE__[resolved].exports;
    }
    return require(reqPath);
  };
}
`;

for (const mod of modules) {
  const fullPath = path.join(ROOT_DIR, mod.file);
  const rawContent = fs.readFileSync(fullPath, 'utf8');
  // Оборачиваем фабрику модуля
  bundleCode += `
__define('${mod.id}', function(module, exports, require) {
${rawContent}
});
`;
}

// Добавляем точку входа
bundleCode += `
// Точка входа автономного приложения
(function() {
  const { startServer } = __app_require('main')('server/bridge-server');
  const PORT = process.env.PORT || 34567;
  console.log('='.repeat(60));
  console.log('  Viber Transfer PC - Автономный запуск (Standalone .EXE)');
  console.log('  Адрес веб-интерфейса: http://localhost:' + PORT);
  console.log('='.repeat(60));

  startServer(PORT).then(() => {
    const startCmd = process.platform === 'win32' ? 'start' : (process.platform === 'darwin' ? 'open' : 'xdg-open');
    require('node:child_process').exec(startCmd + ' http://localhost:' + PORT);
  }).catch((err) => {
    console.error('Ошибка запуска сервера:', err);
  });
})();
`;

const bundlePath = path.join(DIST_DIR, 'bundle.js');
fs.writeFileSync(bundlePath, bundleCode, 'utf8');
console.log(`   Создан бандл: ${bundlePath} (${Math.round(bundleCode.length / 1024)} KB)`);

// 4. Генерация конфигурации Node SEA
console.log('[3/5] Создание конфигурации Node SEA...');
const seaConfigPath = path.join(DIST_DIR, 'sea-config.json');
const targetExePath = path.join(DIST_DIR, 'ViberTransfer.exe');

const seaConfig = {
  main: path.relative(ROOT_DIR, bundlePath).replace(/\\/g, '/'),
  output: path.relative(ROOT_DIR, targetExePath).replace(/\\/g, '/'),
  disableExperimentalSEAWarning: true
};

fs.writeFileSync(seaConfigPath, JSON.stringify(seaConfig, null, 2), 'utf8');

// 5. Компиляция в исполняемый файл
console.log('[4/5] Компиляция Windows PE (.exe) через Node SEA...');
const nodeExe = process.execPath;
try {
  execSync(`"${nodeExe}" --build-sea "${seaConfigPath}"`, {
    cwd: ROOT_DIR,
    stdio: 'inherit'
  });
} catch (err) {
  console.error('Ошибка сборки SEA:', err.message);
  process.exit(1);
}

// 6. Копирование в корень проекта для мгновенного доступа пользователя
console.log('[5/5] Финализация и размещение в корне проекта...');
const rootExePath = path.join(ROOT_DIR, 'ViberTransfer.exe');
if (fs.existsSync(targetExePath)) {
  fs.copyFileSync(targetExePath, rootExePath);
  const stat = fs.statSync(rootExePath);
  const sizeMb = (stat.size / (1024 * 1024)).toFixed(2);
  console.log('='.repeat(70));
  console.log(`✅ УСПЕШНО СОБРАН АВТОНОМНЫЙ ИСПОЛНЯЕМЫЙ ФАЙЛ:`);
  console.log(`   Файл: ${rootExePath}`);
  console.log(`   Размер: ${sizeMb} MB (включает Node.js runtime, SQLite движок и GUI)`);
  console.log('='.repeat(70));
  console.log('Пользователь может запускать ViberTransfer.exe в один клик без Node.js!');
} else {
  console.error('Ошибка: ViberTransfer.exe не был сгенерирован.');
  process.exit(1);
}
